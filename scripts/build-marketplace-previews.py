#!/usr/bin/env python3
"""Convert checked-in simulator screenshots to compact LVGL 4-bit previews.
Requires Pillow; rerun after replacing screenshots in assets/marketplace.
"""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
apps=['agent-usage','system-monitor','iss-tracker','stocks','transit','planes','home-assistant']
out=['// Generated by scripts/build-marketplace-previews.py; do not edit.']
for app in apps:
    image=Image.open(root/'assets/marketplace'/f'{app}.png').convert('RGB').resize((120,180),Image.Resampling.LANCZOS).quantize(colors=16)
    palette=image.getpalette();data=bytearray()
    for i in range(16):
        r,g,b=palette[i*3:i*3+3];data.extend([b,g,r,255])
    pixels=image.tobytes()
    data.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2))
    name=app.replace('-','_')
    out.append(f'static const uint8_t {name}_pixels[]={{')
    out.extend(','.join(str(v) for v in data[i:i+32])+',' for i in range(0,len(data),32))
    out.append('};')
    out.append(f'static const lv_image_dsc_t {name}_preview=[]{{lv_image_dsc_t d={{}};d.header.magic=LV_IMAGE_HEADER_MAGIC;d.header.cf=LV_COLOR_FORMAT_I4;d.header.w=120;d.header.h=180;d.header.stride=60;d.data_size=sizeof({name}_pixels);d.data={name}_pixels;return d;}}();')
(root/'src/experimental/MarketplacePreviews.inc').write_text('\n'.join(out)+'\n')
print('Generated',len(apps),'previews;',len(apps)*(64+10800),'image bytes')
