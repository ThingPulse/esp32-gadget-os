#!/usr/bin/env python3
"""Generate the flash-resident catalogue; no runtime JSON dependency."""
import json
import re
from pathlib import Path
root = Path(__file__).resolve().parent.parent
messages = json.loads((root / 'translations/de.json').read_text())
# Preserve printf argument types/order; translations must not change the contract.
pattern = re.compile(r'(?<!%)%(?!%)[-+ #0]*\d*(?:\.\d+)?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcsp]')
for en, de in messages.items():
    assert pattern.findall(en) == pattern.findall(de), f'Format mismatch: {en!r}'
# Byte ordering matches strcmp on UTF-8 strings in the embedded lookup.
lines = ['// Generated by scripts/generate-translations.py; edit translations/de.json.', 'static const Message messages[] = {']
for en in sorted(messages, key=lambda value: value.encode('utf-8')):
    lines.append(' {' + json.dumps(en, ensure_ascii=False) + ', ' + json.dumps(messages[en], ensure_ascii=False) + '},')
lines.append('};')
(root / 'src/ui/GermanMessages.inc').write_text('\n'.join(lines)+'\n')
