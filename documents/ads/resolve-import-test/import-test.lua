-- Run in Resolve's Lua console with dofile('/absolute/path/import-test.lua').
-- Uses Resolve's in-app API, which is available in the tested Free installation.
local base = debug.getinfo(1, 'S').source:sub(2):match('(.*/)')
local log = assert(io.open(base..'test-result.log', 'w'))
local function note(message) log:write(message..'\n'); log:flush(); print(message) end
local function run()
local r = resolve or fusion:GetResolve()
local pm = r:GetProjectManager()
assert(pm:SaveProject())
local p = pm:GetCurrentProject()
assert(p:GetName() == 'ThingPulse Ad Import Test', 'Open the separate import-test project first')
local mp = p:GetMediaPool()
local t = assert(mp:ImportTimelineFromFile(base..'import-test.otio', {timelineName='ThingPulse - 8 second import test'}), 'OTIO import failed')
p:SetCurrentTimeline(t)
note('OTIO imported successfully')
assert(#t:GetItemListInTrack('video',1) == 2, 'Expected two shots')
assert(#t:GetItemListInTrack('audio',1) == 1, 'Expected one music clip')
assert(t:GetEndFrame()-t:GetStartFrame() == 240, 'Expected 8 seconds at 30fps')
t:AddTrack('video')
local placeholder = assert(mp:ImportMedia({base..'media/title-placeholder.png'})[1])
local title = assert(mp:AppendToTimeline({{mediaPoolItem=placeholder,
    startFrame=0, endFrame=150, recordFrame=t:GetStartFrame(), mediaType=1, trackIndex=2}})[1])
local comp = assert(title:AddFusionComp())
local textTool = assert(comp:AddTool('TextPlus'))
local output = comp:FindTool('MediaOut1') or comp:AddTool('MediaOut')
output:ConnectInput('Input',textTool)
textTool:SetInput('StyledText', 'Build something\nyou\'ll use every day.')
textTool:SetInput('Font', 'Helvetica Neue')
textTool:SetInput('Style', 'Bold')
textTool:SetInput('Size', 0.035)
textTool:SetInput('Center', {0.18,0.6})
textTool:SetInput('Red1', 0.05)
textTool:SetInput('Green1', 0.07)
textTool:SetInput('Blue1', 0.09)
assert(pm:SaveProject())
assert(t:Export(base..'ThingPulse-import-test.drt',r.EXPORT_DRT))
assert(pm:ExportProject(p:GetName(),base..'ThingPulse-import-test.drp'))
note('IMPORT TEST COMPLETE: two shots, separate music, native editable Text+, 8 seconds.')
end
local ok, err = xpcall(run, debug.traceback)
if not ok then note('FAILED: '..tostring(err)) end
log:close()
